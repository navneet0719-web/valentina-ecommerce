function slugify(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

// Helper to pick genuine verified photos by category key
function getCategoryPhotos(
  poolKey: keyof typeof VERIFIED_PHOTO_POOL.commons,
  djCategories: string[],
  seedIndex: number
): Array<{ url: string; source: string }> {
  const djMatches = VERIFIED_PHOTO_POOL.dummyJson.filter((d) =>
    djCategories.includes(d.category)
  );
  const djUrls: Array<{ url: string; source: string }> = [];
  for (const item of djMatches) {
    for (const img of item.images) {
      djUrls.push({ url: img, source: item.source });
    }
  }

  const commonsList = VERIFIED_PHOTO_POOL.commons[poolKey] || [];
  const commonsUrls: Array<{ url: string; source: string }> = commonsList.map((c) => ({
    url: c.url,
    source: c.source,
  }));

  // Combine DummyJSON studio product shots & Wikimedia Commons licensed product photography
  const combined =
    djCategories.includes('beauty') ||
    djCategories.includes('skin-care') ||
    djCategories.includes('fragrances') ||
    djCategories.includes('sunglasses') ||
    djCategories.includes('womens-watches') ||
    djCategories.includes('womens-bags')
      ? [...djUrls, ...commonsUrls]
      : [...commonsUrls, ...djUrls];

  if (combined.length === 0) {
    return [
      {
        url: '/src/assets/images/valentina_jewellery_collection_1791643634883.jpg',
        source: 'VALENTINA Studio Photography',
      },
    ];
  }

  const result: Array<{ url: string; source: string }> = [];
  for (let i = 0; i < 4; i++) {
    const idx = (seedIndex * 3 + i * 5) % combined.length;
    result.push(combined[idx]);
  }
  return result;
}

