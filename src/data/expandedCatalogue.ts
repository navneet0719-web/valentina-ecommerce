const SERIES_DESCRIPTOR = [
  'Edition II',
  'Grande Silhouette',
  'Petite Proportions',
  'Artisan Filigree Series',
  'Heirloom Edit',
  'Pavé Accent Series',
  'Dual-Tone Edition',
  'Festive Zari Edit',
];

export function generateExpandedCatalogue(): Product[] {
  const expanded: Product[] = [];
  let prodNumber = 33; // Continues seamlessly after prod-01..prod-32
  const usedSlugs = new Set<string>();

  for (const group of CATEGORY_GROUPS) {
    let createdInGroup = 0;
    let pass = 0;

    while (createdInGroup < group.targetCount) {
      for (let i = 0; i < group.blueprints.length && createdInGroup < group.targetCount; i++) {
        const bp = group.blueprints[i];
        const prefix = group.silhouettePrefixes[(prodNumber + i) % group.silhouettePrefixes.length];
        const seriesSuffix = pass === 0 ? '' : ` — ${ prefix } ${ SERIES_DESCRIPTOR[(pass - 1) % SERIES_DESCRIPTOR.length] }`;
        const distinctName = pass === 0 ? bp.name : `${prefix} ${bp.name.replace(/^[A-Za-z-]+\s+/, '')} (${SERIES_DESCRIPTOR[(pass + i) % SERIES_DESCRIPTOR.length]})`;

        let candidateSlug = slugify(distinctName);
        if (usedSlugs.has(candidateSlug)) {
          candidateSlug = `${candidateSlug}-${prodNumber}`;
        }
        usedSlugs.add(candidateSlug);

        const productId = `prod-${prodNumber}`;
        const skuPrefix = `VAL-${group.categoryName.slice(0, 3).toUpperCase()}-${String(prodNumber).padStart(3, '0')}`;
        const priceAdjust = pass === 0 ? 0 : ((prodNumber * 7) % 5) * 60 - 100;
        const basePrice = Math.max(290, bp.basePrice + priceAdjust);
        const compareAtPrice = bp.compareAtPrice
          ? Math.max(basePrice + 200, bp.compareAtPrice + priceAdjust)
          : undefined;

        const photos = getCategoryPhotos(group.poolKey, group.djCategories, prodNumber);
        const primaryPhotoSource = photos[0]?.source || 'Verified Supplier Product Library';

        const variants: ProductVariant[] = [];
        const colorsToUse = bp.colors.slice(0, 3);
        const optionsToUse = bp.options.slice(0, 3);

        let vIdx = 1;
        for (let cIdx = 0; cIdx < colorsToUse.length; cIdx++) {
          const colorObj = colorsToUse[cIdx];
          for (let oIdx = 0; oIdx < optionsToUse.length; oIdx++) {
            // Create 3 to 5 rich variants per product without bloating memory
            if (cIdx > 0 && oIdx > 0 && variants.length >= 4) continue;
            const secOpt = optionsToUse[oIdx];
            const optPriceDelta = oIdx * 50;
            const varPrice = basePrice + optPriceDelta;
            const varCompare = compareAtPrice ? compareAtPrice + optPriceDelta : undefined;
            const sku = `${skuPrefix}-V${vIdx}`;

            const angleLabels: Array<{ angle: ProductImage['angle']; label: string }> = [
              { angle: 'front', label: 'Primary Product View' },
              { angle: 'profile', label: 'Angle & Silhouette View' },
              { angle: 'detail', label: 'Finish & Texture Detail' },
              { angle: 'styled', label: 'Presentation View' },
            ];

            const images: ProductImage[] = angleLabels.map((ang, aIdx) => {
              const photoItem = photos[(cIdx + aIdx) % photos.length];
              return {
                url: photoItem.url,
                alt: `${distinctName} in ${colorObj.name} (${secOpt}) — ${ang.label}`,
                angle: ang.angle,
                caption: `${ang.label} · ${colorObj.name} · ${secOpt}`,
              };
            });

            const stockRoll = (prodNumber + vIdx) % 11;
            const stockStatus: ProductVariant['stockStatus'] =
              stockRoll === 0 ? 'low_stock' : 'in_stock';
            const stockQuantity = stockRoll === 0 ? 3 : 10 + ((prodNumber + vIdx) % 18);

            variants.push({
              id: `${productId}-v${vIdx}`,
              sku,
              color: colorObj.name,
              colorHex: colorObj.hex,
              secondaryOption: secOpt,
              price: varPrice,
              compareAtPrice: varCompare,
              stockStatus,
              stockQuantity,
              images,
            });
            vIdx++;
          }
        }

        const collectionsSet = new Set<string>([
          ...group.defaultCollections,
          ...(bp.extraCollections || []),
          ...bp.occasions,
        ]);

        const dayOffset = prodNumber % 28;
        const createdAt = `2026-09-${String(Math.max(1, 28 - dayOffset)).padStart(2, '0')}`;

        const specs: Array<{ label: string; value: string }> = [
          { label: 'Department', value: group.department || group.categoryName },
          { label: 'Category', value: group.categoryName },
          { label: 'Subcategory / Style', value: bp.subcategory },
          { label: 'Brand / Supplier Line', value: bp.brand },
          { label: 'Material & Composition', value: bp.material },
          { label: 'Selectable Options', value: `${bp.secondaryLabel} (${bp.options.length} options)` },
          { label: 'Photography Source', value: primaryPhotoSource },
          ...(bp.specs || []),
        ];

        const defaultSizingNote =
          group.categoryName === 'Bangles'
            ? BANGLE_SIZING_EXPLANATION
            : group.department === 'Makeup & Beauty'
            ? bp.sizingOrUsageNote ||
              `Shade, finish, and pack options are selectable above. Perform a patch test prior to first use and store in a cool, dry place away from direct sunlight.`
            : bp.sizingOrUsageNote;

        expanded.push({
          id: productId,
          slug: candidateSlug,
          name: distinctName,
          department: group.department,
          category: group.categoryName as Product['category'],
          subcategory: bp.subcategory,
          brand: bp.brand,
          occasion: bp.occasions,
          photoSource: primaryPhotoSource,
          sizingNote: defaultSizingNote,
          collections: Array.from(collectionsSet),
          basePrice,
          compareAtPrice,
          isNewArrival: Boolean(bp.isNew && pass === 0),
          isBestseller: Boolean(bp.isBest && pass === 0),
          createdAt,
          shortSummary: `${bp.summary}${seriesSuffix ? ` (${bp.subcategory})` : ''}`,
          description: `${distinctName} is part of VALENTINA’s ${group.categoryName} collection (${bp.subcategory}). Crafted with ${bp.material.toLowerCase()}, this piece is designed to bring refined elegance and practical comfort to your ${bp.occasions
            .map((o) => o.replace(/-/g, ' '))
            .join(', ')} wardrobe. ${defaultSizingNote || ''}`,
          features: [
            `Authentic ${bp.subcategory} silhouette from ${bp.brand}`,
            `Crafted with ${bp.material}`,
            `Selectable ${bp.secondaryLabel.toLowerCase()} and colour/shade varieties on this page`,
            `Inspected for smooth finish, skin-friendly comfort, and secure packaging`,
          ],
          specifications: specs,
          materialAndFinish: bp.material,
          careInstructions: group.careList,
          secondaryDimensionLabel: bp.secondaryLabel,
          variants,
          relatedSlugs: [],
          faqs: [
            {
              question: `What options can I select for ${distinctName}?`,
              answer: `You can choose your preferred Colour/Shade and ${bp.secondaryLabel} directly above before adding to your bag. Price and stock status update automatically for each variety.`,
            },
            ...(group.categoryName === 'Bangles'
              ? [
                  {
                    question: 'How do Indian bangle sizes (2.2 to 2.10) work?',
                    answer: BANGLE_SIZING_EXPLANATION,
                  },
                ]
              : []),
          ],
          seoTitle: `${distinctName} — ${bp.subcategory} | VALENTINA`,
          metaDescription: `Shop ${distinctName} (${bp.subcategory}) at VALENTINA. ${bp.summary}`,
        });

        prodNumber++;
        createdInGroup++;
      }
      pass++;
    }
  }

  return expanded;
}
